"""Regenerate data/eval_dataset.json and questions.md from crunchbench/questions.py.

    uv run scripts/build_dataset.py

Fails without writing anything if any ground truth is ambiguous.
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from crunchbench.config import load_settings
from crunchbench.data import ROOT
from crunchbench.dataset import DATASET_PATH, write_dataset
from crunchbench.questions import QUESTIONS, RULES


def write_questions_md(cases: list[dict]) -> None:
    answers = defaultdict(dict)
    for c in cases:
        answers[c["question_id"]][c["tokens"]] = c["reference"]
    sizes = sorted({c["tokens"] for c in cases})

    lines = [
        "# CrunchBench Questions",
        "",
        "Generated by `scripts/build_dataset.py`. Do not edit by hand.",
        "",
        "Every question is sent with these rules:",
        "",
        RULES,
        "",
    ]
    for difficulty in ["Easy", "Medium", "Hard", "Very Hard"]:
        lines += [f"## {difficulty}", ""]
        for q in [q for q in QUESTIONS if q.difficulty == difficulty]:
            lines += [f"### {q.id}. {q.text}", "", "| Context | Answer |", "| --- | --- |"]
            for t in sizes:
                ref = answers[q.id][t].replace("\n", "<br>").replace("|", "\\|")
                lines.append(f"| {t // 1000}k | {ref} |")
            lines.append("")
    (ROOT / "questions.md").write_text("\n".join(lines))


def main() -> None:
    dataset = write_dataset(load_settings().context_sizes)
    write_questions_md(dataset["cases"])
    print(f"Wrote {len(dataset['cases'])} cases to {DATASET_PATH.relative_to(ROOT)} and questions.md")


if __name__ == "__main__":
    main()
